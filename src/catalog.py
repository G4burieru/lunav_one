"""Pre-computed Catalog Site data in data/catalog/ (see docs/adr/0001). Owner: Gabriel.

Generated by `python -m scripts.precompute`. Per site:
    <slug>_ephemerides.csv.gz   hourly ephemerides (same columns as get_ephemerides_data)
    <slug>_terrain.npz          Site Neighborhood: `east`, `north` offsets (m) and `horizons` (N x 360,
                                centidegrees, site-frame azimuths, asset height ASSET_HEIGHT_M)
manifest.json records the coordinates each site was computed for; data for moved sites is ignored.
"""
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

DATA_DIR = Path(__file__).resolve().parent.parent / "data" / "catalog"
START, END = "2027-01-01", "2029-01-01"
ASSET_HEIGHT_M = 2.0
NEIGHBORHOOD_RADIUS_M = 2000
NEIGHBORHOOD_SPACING_M = 100


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def neighborhood_offsets():
    """East and north offsets (m) of the Site Neighborhood points; the site itself is (0, 0)."""
    steps = np.arange(-NEIGHBORHOOD_RADIUS_M, NEIGHBORHOOD_RADIUS_M + 1, NEIGHBORHOOD_SPACING_M)
    east, north = np.meshgrid(steps, steps)
    inside = east**2 + north**2 <= NEIGHBORHOOD_RADIUS_M**2
    return east[inside].astype(float), north[inside].astype(float)


def read_manifest(data_dir=DATA_DIR):
    path = data_dir / "manifest.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def load_site(name, site, data_dir=DATA_DIR):
    """(ephemerides DataFrame, neighborhood dict or None) for a catalog site, or None if not pre-computed for its
    current coordinates. The neighborhood dict has `east`, `north` (m) and `horizons` (N x 360, deg)."""
    entry = read_manifest(data_dir).get(name)
    if not entry or (entry["lat"], entry["lon"]) != (site["lat"], site["lon"]):
        return None
    ephemerides = pd.read_csv(data_dir / f"{slug(name)}_ephemerides.csv.gz", parse_dates=["time"])
    terrain_path = data_dir / f"{slug(name)}_terrain.npz"
    if not terrain_path.exists():
        return ephemerides, None
    with np.load(terrain_path) as z:
        neighborhood = {"east": z["east"], "north": z["north"], "horizons": z["horizons"] / 100.0}
    return ephemerides, neighborhood
